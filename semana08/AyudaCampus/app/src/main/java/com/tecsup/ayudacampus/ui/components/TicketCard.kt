@Composable
fun TicketCard(
    detalle: TicketConDetalle,
    alPulsar: () -> Unit,
    modifier: Modifier = Modifier,
    mostrarCliente: Boolean = false
) {
    val ticket = detalle.ticket
    val prioridad = Prioridad.valueOf(ticket.prioridad)
    val estado = EstadoTicket.valueOf(ticket.estado)

    val subtitulo = buildString {
        append(numeroTicket(ticket.id))
        if (mostrarCliente) detalle.cliente?.let { append(" · ${it.nombre}") }
        if (ticket.ubicacion.isNotBlank()) append(" · ${ticket.ubicacion}")
    }

    Card(
        onClick = alPulsar,
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        border = BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
        modifier = modifier.fillMaxWidth()
    ) {
        Row(modifier = Modifier.height(IntrinsicSize.Min)) {
            Box(
                modifier = Modifier
                    .width(5.dp)
                    .fillMaxHeight()
                    .background(colorPrioridad(prioridad))
            )
            Column(
                modifier = Modifier
                    .weight(1f)
                    .padding(14.dp)
            ) {
                Row {
                    Box(
                        contentAlignment = Alignment.Center,
                        modifier = Modifier
                            .size(44.dp)
                            .clip(RoundedCornerShape(12.dp))
                            .background(MaterialTheme.colorScheme.primaryContainer)
                    ) {
                        Icon(
                            iconoCategoria(detalle.categoria?.icono ?: "tag"),
                            contentDescription = detalle.categoria?.nombre,
                            tint = MaterialTheme.colorScheme.primary
                        )
                    }
                    Spacer(Modifier.width(12.dp))
                    Column(modifier = Modifier.weight(1f)) {
                        Text(
                            ticket.titulo,
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.SemiBold,
                            maxLines = 2,
                            overflow = TextOverflow.Ellipsis
                        )
                        Text(
                            subtitulo,
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            maxLines = 1,
                            overflow = TextOverflow.Ellipsis
                        )
                    }
                }
                Spacer(Modifier.height(12.dp))
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(6.dp)
                ) {
                    EstadoChip(estado)
                    PrioridadChip(prioridad)
                    Spacer(Modifier.weight(1f))
                    Text(
                        tiempoRelativo(ticket.fecha),
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
        }
    }
}